/**
 * 读取平台模板库数据：优先取 localStorage（用户在模板库管理页的增删改），
 * 无缓存或缓存缺条目时用默认数据兜底并补种。
 */
export function loadPlatformTemplates() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (!saved) return DEFAULT_PLATFORM_TEMPLATES.slice()
    const parsed = JSON.parse(saved)
    if (!Array.isArray(parsed) || !parsed.length) return DEFAULT_PLATFORM_TEMPLATES.slice()
    // 结构升级：模板的填报场景（variants）、报告正文（body）与章节结构（sections）由代码维护、界面不可编辑，
    // 故当默认数据的结构指纹与缓存不一致时，视为结构已升级，以默认数据覆盖该条目。
    // 指纹纳入：scope（平台场景改名推送）+ caliber.standardCode（编制依据变更）+
    //           body/sections 的内容哈希（报表结构或预置行数据补全时推送，如品种目录补全、预置计量单位）。
    const structHash = s => { let h = 5381; for (let i = 0; i < s.length; i++) { h = ((h << 5) + h + s.charCodeAt(i)) >>> 0 } return h.toString(36) }
    const structCount = x => [
      x.scope || '',
      (x.caliber && x.caliber.standardCode) || '',
      structHash(JSON.stringify({ body: x.body || null, sections: x.sections || null, variants: x.variants || null }))
    ].join('-')
    const list = parsed.map(t => {
      const def = DEFAULT_PLATFORM_TEMPLATES.find(d => d.id === t.id)
      if (!def) return t
      return structCount(t) === structCount(def) ? t : { ...def }
    })
    const existing = new Set(list.map(t => t.id))
    const pending = MERGE_IDS.filter(id => !existing.has(id))
    const merged = pending.length
      ? list.concat(DEFAULT_PLATFORM_TEMPLATES.filter(t => pending.includes(t.id)))
      : list
    if (pending.length || merged.some((t, i) => t !== parsed[i])) {
      try { localStorage.setItem(STORAGE_KEY, JSON.stringify(merged)) } catch (e) { /* ignore */ }
    }
    return merged
  } catch (e) {
    return DEFAULT_PLATFORM_TEMPLATES.slice()
  }
}
